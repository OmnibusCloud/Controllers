#!/usr/bin/env python3
"""Generates CorpusCasingTable.g.cs: the lower-case table of the Corpus controller.

The table is the Simple_Lowercase_Mapping of the Unicode Character Database (field 13 of
UnicodeData.txt) of one named Unicode version, with the exceptions listed in EXCEPTIONS. The
controller lower-cases with this table and never with the globalization library of the machine
it runs on, so that a document gives the same language n-grams and the same MinHash tokens on
every node.

Usage:
    python -I generate_casing_table.py <path to UnicodeData.txt> [<output .g.cs>]

The input is the file published at SOURCE; its SHA-256 must be SOURCE_SHA256 (the script
refuses another file). The file itself is not kept in the repository: only the table derived
from it is, under the Unicode License v3 (LICENSE-unicode.txt beside the controller).

To move to another Unicode version: change VERSION, SOURCE and SOURCE_SHA256, run the script,
and treat the result as a new stage set (the products of documents that hold a code point whose
mapping changed move, and with them the pins the tests hold).
"""
import hashlib
import os
import sys

VERSION = "16.0.0"
SOURCE = "https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt"
SOURCE_SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"

# Code points the table maps otherwise than the Unicode data does, with the reason.
#   U+0130 LATIN CAPITAL LETTER I WITH DOT ABOVE maps to itself, not to U+0069: .NET's invariant
#   lower-casing has always kept it (on every platform, whatever library answers), every product
#   and every language pack made so far has it so, and mapping it to "i" would merge the Turkish
#   dotted capital with the dotless one's lower case.
EXCEPTIONS = {0x0130: 0x0130}

FIELD_CODE_POINT = 0
FIELD_SIMPLE_LOWERCASE = 13


def read_mappings(path):
    with open(path, "rb") as handle:
        data = handle.read()

    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"{path} hashes to {digest}, not the {SOURCE_SHA256} of UnicodeData.txt {VERSION}")

    mappings = {}
    for line in data.decode("ascii").splitlines():
        fields = line.split(";")
        if len(fields) <= FIELD_SIMPLE_LOWERCASE or not fields[FIELD_SIMPLE_LOWERCASE]:
            continue

        mappings[int(fields[FIELD_CODE_POINT], 16)] = int(fields[FIELD_SIMPLE_LOWERCASE], 16)

    for code_point, lower in EXCEPTIONS.items():
        if lower == code_point:
            mappings.pop(code_point, None)
        else:
            mappings[code_point] = lower

    return dict(sorted(mappings.items()))


def table_digest(mappings):
    """SHA-256 of the table as text: one 'XXXX;YYYY' line per mapping, upper-case hex, LF."""
    text = "".join(f"{code_point:04X};{lower:04X}\n" for code_point, lower in mappings.items())
    return hashlib.sha256(text.encode("ascii")).hexdigest()


def render(mappings):
    pairs = [f"0x{code_point:04X}, 0x{lower:04X}," for code_point, lower in mappings.items()]
    rows = ["        " + " ".join(pairs[index:index + 6]) for index in range(0, len(pairs), 6)]
    exceptions = ", ".join(f"U+{code_point:04X} to U+{lower:04X}" for code_point, lower in sorted(EXCEPTIONS.items()))

    return "\n".join([
        "// <auto-generated>",
        "//   Generated by Text/Casing/generate_casing_table.py from UnicodeData.txt of Unicode " + VERSION + ".",
        "//   Do not edit: change the script and run it again.",
        "//",
        "//   Source:  " + SOURCE,
        "//   SHA-256: " + SOURCE_SHA256,
        "//   Licence: Unicode License v3 (LICENSE-unicode.txt). Copyright (c) 1991-2026 Unicode, Inc.",
        "// </auto-generated>",
        "",
        "namespace OutWit.Controller.AI.Corpus.Text.Casing;",
        "",
        "/// <summary>",
        "/// The lower-case table of the controller: the Simple_Lowercase_Mapping of Unicode " + VERSION,
        "/// (UnicodeData.txt, field 13), with these exceptions: " + exceptions + ".",
        "/// </summary>",
        "internal static class CorpusCasingTable",
        "{",
        "    #region Constants",
        "",
        "    /// <summary>The Unicode version the table is made from.</summary>",
        "    public const string UNICODE_VERSION = \"" + VERSION + "\";",
        "",
        "    /// <summary>Where the data file is published.</summary>",
        "    public const string SOURCE = \"" + SOURCE + "\";",
        "",
        "    /// <summary>The SHA-256 of the data file the table is made from.</summary>",
        "    public const string SOURCE_SHA256 = \"" + SOURCE_SHA256 + "\";",
        "",
        "    /// <summary>The SHA-256 of the table itself: one \"XXXX;YYYY\" line per mapping, upper-case hex, LF.</summary>",
        "    public const string TABLE_SHA256 = \"" + table_digest(mappings) + "\";",
        "",
        "    /// <summary>How many code points have a lower case of their own.</summary>",
        "    public const int MAPPINGS = " + str(len(mappings)) + ";",
        "",
        "    #endregion",
        "",
        "    #region Properties",
        "",
        "    /// <summary>The mappings as pairs, ascending by code point: a code point, then its lower case.</summary>",
        "    public static ReadOnlySpan<int> Pairs =>",
        "    [",
        *rows,
        "    ];",
        "",
        "    #endregion",
        "}",
        "",
    ])


def main(arguments):
    if not arguments:
        raise SystemExit(__doc__)

    output = arguments[1] if len(arguments) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "CorpusCasingTable.g.cs")
    mappings = read_mappings(arguments[0])
    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(mappings))

    print(f"{len(mappings)} mappings of Unicode {VERSION}, table sha256 {table_digest(mappings)} -> {output}")


if __name__ == "__main__":
    main(sys.argv[1:])
