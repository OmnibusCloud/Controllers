using System.Text;

namespace OutWit.Controller.AI.Corpus.Text.Casing;

/// <summary>
/// The controller's own case handling, in place of the globalization library of the machine it
/// runs on. .NET answers <c>ToLowerInvariant</c> and the case-insensitive comparisons from ICU,
/// from Windows NLS or from its own table, depending on the machine; the three differ for
/// hundreds of code points, and a document's language n-grams and MinHash tokens are made of
/// lower-cased letters, so two honest nodes could sign one document differently. Everything of
/// case that reaches a product goes through here:
/// <list type="bullet">
/// <item><see cref="ToLower(Rune)"/>: the Simple_Lowercase_Mapping of one named Unicode version
/// (<see cref="UNICODE_VERSION"/>), from a table generated by a committed script
/// (<c>generate_casing_table.py</c>) and pinned by its hash.</item>
/// <item>The ASCII comparisons (<see cref="EqualsIgnoreAsciiCase"/>,
/// <see cref="ContainsIgnoreAsciiCase"/>, <see cref="ToLowerAscii"/>): for names and phrases that
/// are ASCII by definition (HTML tags, header names, media types, a fixed English phrase). Only
/// A to Z fold; no other character ever equals an ASCII letter.</item>
/// </list>
/// </summary>
public static class CorpusCasing
{
    #region Constants

    /// <summary>The Unicode version of the lower-case table.</summary>
    public const string UNICODE_VERSION = CorpusCasingTable.UNICODE_VERSION;

    /// <summary>The SHA-256 of the lower-case table (one "XXXX;YYYY" line per mapping): what a stage set's fingerprint and the tests pin.</summary>
    public const string TABLE_SHA256 = CorpusCasingTable.TABLE_SHA256;

    private const int BMP_SIZE = 0x10000;

    #endregion

    #region Fields

    /// <summary>The lower case of every code unit of the Basic Multilingual Plane (itself where it has none).</summary>
    private static readonly char[] BMP = BuildBmp();

    /// <summary>The mappings above the Basic Multilingual Plane, ascending.</summary>
    private static readonly (int From, int To)[] ASTRAL = BuildAstral();

    #endregion

    #region Functions

    /// <summary>The lower case of a code point by the controller's table.</summary>
    /// <param name="rune">The code point.</param>
    /// <returns>Its simple lower-case mapping, or itself.</returns>
    public static Rune ToLower(Rune rune)
    {
        var value = rune.Value;
        if (value < BMP_SIZE)
            return new Rune(BMP[value]);

        var low = 0;
        var high = ASTRAL.Length - 1;
        while (low <= high)
        {
            var middle = (low + high) >>> 1;
            var from = ASTRAL[middle].From;
            if (from == value)
                return new Rune(ASTRAL[middle].To);

            if (from < value)
                low = middle + 1;
            else
                high = middle - 1;
        }

        return rune;
    }

    /// <summary>The lower case of a UTF-16 code unit by the controller's table (a surrogate is itself).</summary>
    /// <param name="value">The code unit.</param>
    /// <returns>Its simple lower-case mapping, or itself.</returns>
    public static char ToLower(char value)
    {
        return BMP[value];
    }

    /// <summary>An ASCII upper-case letter as its lower case; any other character as it is.</summary>
    /// <param name="value">The character.</param>
    /// <returns>The character, folded when it is A to Z.</returns>
    public static char ToLowerAscii(char value)
    {
        return value is >= 'A' and <= 'Z' ? (char)(value | 0x20) : value;
    }

    /// <summary>A text with its ASCII upper-case letters lower-cased and nothing else changed.</summary>
    /// <param name="text">The text.</param>
    /// <returns>The folded text (the same instance when nothing folds).</returns>
    public static string ToLowerAscii(string text)
    {
        var first = -1;
        for (var index = 0; index < text.Length; index++)
        {
            if (text[index] is >= 'A' and <= 'Z')
            {
                first = index;
                break;
            }
        }

        if (first < 0)
            return text;

        return string.Create(text.Length, text, static (span, source) =>
        {
            for (var index = 0; index < span.Length; index++)
                span[index] = ToLowerAscii(source[index]);
        });
    }

    /// <summary>Whether a text equals an ASCII word, A to Z folding and nothing else.</summary>
    /// <param name="text">The text.</param>
    /// <param name="ascii">The word to compare with, ASCII.</param>
    /// <returns>True when they are equal up to the case of ASCII letters.</returns>
    public static bool EqualsIgnoreAsciiCase(ReadOnlySpan<char> text, ReadOnlySpan<char> ascii)
    {
        if (text.Length != ascii.Length)
            return false;

        for (var index = 0; index < text.Length; index++)
        {
            if (ToLowerAscii(text[index]) != ToLowerAscii(ascii[index]))
                return false;
        }

        return true;
    }

    /// <summary>Whether a text starts with an ASCII word, A to Z folding and nothing else.</summary>
    /// <param name="text">The text.</param>
    /// <param name="ascii">The word, ASCII.</param>
    /// <returns>True when the text starts with it.</returns>
    public static bool StartsWithIgnoreAsciiCase(ReadOnlySpan<char> text, ReadOnlySpan<char> ascii)
    {
        return text.Length >= ascii.Length && EqualsIgnoreAsciiCase(text[..ascii.Length], ascii);
    }

    /// <summary>Where an ASCII phrase first stands in a text, A to Z folding and nothing else.</summary>
    /// <param name="text">The text.</param>
    /// <param name="ascii">The phrase, ASCII, not empty.</param>
    /// <param name="start">Where to start looking.</param>
    /// <returns>The index of the first occurrence at or after <paramref name="start"/>, or -1.</returns>
    public static int IndexOfIgnoreAsciiCase(ReadOnlySpan<char> text, ReadOnlySpan<char> ascii, int start = 0)
    {
        if (ascii.Length == 0)
            return start <= text.Length ? start : -1;

        var first = ToLowerAscii(ascii[0]);
        var last = text.Length - ascii.Length;
        for (var index = Math.Max(0, start); index <= last; index++)
        {
            if (ToLowerAscii(text[index]) == first && EqualsIgnoreAsciiCase(text.Slice(index, ascii.Length), ascii))
                return index;
        }

        return -1;
    }

    /// <summary>Whether a text holds an ASCII phrase, A to Z folding and nothing else.</summary>
    /// <param name="text">The text.</param>
    /// <param name="ascii">The phrase, ASCII.</param>
    /// <returns>True when it does.</returns>
    public static bool ContainsIgnoreAsciiCase(ReadOnlySpan<char> text, ReadOnlySpan<char> ascii)
    {
        return IndexOfIgnoreAsciiCase(text, ascii) >= 0;
    }

    private static char[] BuildBmp()
    {
        var table = new char[BMP_SIZE];
        for (var value = 0; value < BMP_SIZE; value++)
            table[value] = (char)value;

        var pairs = CorpusCasingTable.Pairs;
        for (var index = 0; index < pairs.Length && pairs[index] < BMP_SIZE; index += 2)
            table[pairs[index]] = (char)pairs[index + 1];

        return table;
    }

    private static (int From, int To)[] BuildAstral()
    {
        var pairs = CorpusCasingTable.Pairs;
        var astral = new List<(int From, int To)>();
        for (var index = 0; index < pairs.Length; index += 2)
        {
            if (pairs[index] >= BMP_SIZE)
                astral.Add((pairs[index], pairs[index + 1]));
        }

        return [.. astral];
    }

    #endregion
}
