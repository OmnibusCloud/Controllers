"""numpy's extension modules as python.wasm builtins: the table and the link inputs.

Usage: numpy_builtins.py <numpy-build-dir> <numpy-version> <ext-suffix> <out-dir>

Reads the module archives numpy's meson build produced through wasi-cc (each X<ext-suffix> a
static archive of the module's objects, X<ext-suffix>.deps the libraries it links with) and
writes into <out-dir>:

  npyinittab.h   the builtin table wasinumpy.c registers: each module's full dotted name
                 (numpy/_core/_multiarray_umath -> numpy._core._multiarray_umath) and its
                 PyInit function
  archives/      each module's archive under a name of its own (makesetup takes *.a tokens as
                 libraries, and two packages may have modules of the same name)
  link.txt       the Setup.local tokens: the archives, then the static libraries, -L and -l
                 options their .deps files name, each once

Left out: numpy's test modules (*_tests) and _simd, which only its tests import.
"""

import os
import re
import shutil
import sys

LEFT_OUT = re.compile(r"(^|/)(_[a-z_]*_tests|_simd)$")


def main(build_dir, version, suffix, out_dir):
    modules = []
    for root, dirs, files in os.walk(build_dir):
        dirs.sort()
        for name in sorted(files):
            if name.endswith(suffix):
                path = os.path.join(root, name)
                relative = os.path.relpath(path, build_dir).replace(os.sep, "/")[: -len(suffix)]
                modules.append((relative, path))
    if not modules:
        sys.exit(f"no {suffix} module archives under {build_dir}")

    archives_dir = os.path.join(out_dir, "archives")
    os.makedirs(archives_dir, exist_ok=True)
    entries = []
    archives = []
    libraries = []
    inits = set()
    for relative, path in modules:
        if LEFT_OUT.search(relative):
            print(f"left out: {relative}")
            continue
        if not relative.startswith("numpy/"):
            sys.exit(f"a module outside the numpy package: {relative}")
        dotted = relative.replace("/", ".")
        init = "PyInit_" + relative.rsplit("/", 1)[-1]
        if init in inits:
            sys.exit(f"two modules would share {init}")
        inits.add(init)
        entries.append((dotted, init))
        with open(path, "rb") as f:
            if f.read(8) != b"!<arch>\n":
                sys.exit(f"{relative}{suffix} is not an archive (was it linked by wasi-cc?)")
        archive = os.path.join(archives_dir, dotted.replace(".", "_") + ".a")
        shutil.copyfile(path, archive)
        archives.append(archive)
        with open(path + ".deps", encoding="utf-8") as f:
            for token in f.read().split():
                if token.startswith("-l") or token.startswith("-L"):
                    libraries.append(token)
                else:
                    # meson links from its build directory: a relative path is relative to it
                    libraries.append(os.path.normpath(os.path.join(build_dir, token)))

    seen = set()
    unique = []
    # static libraries first, then -L, then -l: the order a linker reads them best
    for kind in (lambda t: not t.startswith("-"), lambda t: t.startswith("-L"), lambda t: t.startswith("-l")):
        for token in libraries:
            if kind(token) and token not in seen:
                seen.add(token)
                unique.append(token)
    for token in archives + unique:
        if "=" in token or " " in token:
            sys.exit(f"makesetup cannot take this token: {token!r}")

    with open(os.path.join(out_dir, "npyinittab.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by numpy_builtins.py from numpy's module archives. */\n")
        f.write(f'#define PYNP_NUMPY_VERSION "{version}"\n\n')
        for _, init in entries:
            f.write(f"PyObject *{init}(void);\n")
        f.write("\nstatic const struct {\n    const char *name;\n    PyObject *(*initfunc)(void);\n} PYNP_INITTAB[] = {\n")
        for dotted, init in entries:
            f.write(f'    {{"{dotted}", {init}}},\n')
        f.write("};\n")
    with open(os.path.join(out_dir, "link.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(" ".join(archives + unique) + "\n")
    for dotted, _ in entries:
        print(f"builtin: {dotted}")
    print(f"{len(entries)} modules, {len(unique)} libraries and options")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
